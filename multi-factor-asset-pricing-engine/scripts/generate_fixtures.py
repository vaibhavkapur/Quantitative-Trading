#!/usr/bin/env python3
"""Generate deterministic synthetic, reference, and invalid fixtures for mfape.

All data generated by this script is 100% synthetic and deterministic (fixed seeds).
No real market transactions, customer data, or proprietary datasets are used.
"""

from __future__ import annotations

import calendar
import csv
import datetime as dt
import json
from pathlib import Path

import numpy as np

PROJECT_ROOT = Path(__file__).resolve().parents[1]
FIXTURES_DIR = PROJECT_ROOT / "data" / "fixtures"


def month_end_dates(start_year: int, start_month: int, n_months: int) -> list[str]:
    dates: list[str] = []
    year, month = start_year, start_month
    for _ in range(n_months):
        last_day = calendar.monthrange(year, month)[1]
        dates.append(dt.date(year, month, last_day).isoformat())
        month += 1
        if month > 12:
            month = 1
            year += 1
    return dates


def _write_csv(path: Path, fieldnames: list[str], rows: list[dict[str, object]]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("w", newline="", encoding="utf-8") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def generate_reference_hand_calculated() -> None:
    """Exact analytical fixture with orthogonal factors and zero idiosyncratic noise."""
    out_dir = FIXTURES_DIR / "reference_hand_calculated"
    dates = month_end_dates(2020, 1, 6)
    rf = 0.0020

    # Orthogonal centered factors:
    # MKT_RF mean = 0.01, centered = [+0.02, -0.02, +0.02, -0.02, 0.00, 0.00]
    # VAL    mean = 0.005, centered = [+0.01, +0.01, -0.01, -0.01, +0.02, -0.02]
    mkt_rf = np.array([0.030, -0.010, 0.030, -0.010, 0.010, 0.010], dtype=np.float64)
    val = np.array([0.015, 0.015, -0.005, -0.005, 0.025, -0.015], dtype=np.float64)

    true_betas = {
        "P1": {"MKT_RF": 0.8, "VAL": -0.5},
        "P2": {"MKT_RF": 1.0, "VAL": 0.5},
        "P3": {"MKT_RF": 1.2, "VAL": -0.5},
        "P4": {"MKT_RF": 1.4, "VAL": 0.5},
    }

    rf_rows = [{"date": d, "rf": f"{rf:.6f}"} for d in dates]
    factor_rows = [
        {"date": d, "MKT_RF": f"{mkt_rf[t]:.6f}", "VAL": f"{val[t]:.6f}"}
        for t, d in enumerate(dates)
    ]
    asset_rows: list[dict[str, object]] = []
    mem_rows: list[dict[str, object]] = []

    for t, d in enumerate(dates):
        for asset_id, b in true_betas.items():
            exc = b["MKT_RF"] * mkt_rf[t] + b["VAL"] * val[t]
            tot = exc + rf
            asset_rows.append(
                {"date": d, "asset_id": asset_id, "total_return": f"{tot:.10f}"}
            )
            mem_rows.append({"date": d, "asset_id": asset_id, "in_universe": "true"})

    _write_csv(out_dir / "risk_free.csv", ["date", "rf"], rf_rows)
    _write_csv(out_dir / "factor_returns.csv", ["date", "MKT_RF", "VAL"], factor_rows)
    _write_csv(out_dir / "asset_returns.csv", ["date", "asset_id", "total_return"], asset_rows)
    _write_csv(
        out_dir / "portfolio_memberships.csv",
        ["date", "asset_id", "in_universe"],
        mem_rows,
    )

    # Exact closed-form analytical oracle
    oracle = {
        "provenance": "Synthetic hand-calculated analytical fixture (zero idiosyncratic noise, orthogonal factors).",
        "dates": dates,
        "rf": rf,
        "factor_means": {
            "MKT_RF": float(np.mean(mkt_rf)),
            "VAL": float(np.mean(val)),
        },
        "factor_centered_dot_product": float(
            np.dot(mkt_rf - np.mean(mkt_rf), val - np.mean(val))
        ),
        "true_betas": true_betas,
        "expected_two_factor": {
            "alpha_all": 0.0,
            "r_squared_all": 1.0,
            "fm_gamma_0": 0.0,
            "fm_lambda_MKT_RF": float(np.mean(mkt_rf)),
            "fm_lambda_VAL": float(np.mean(val)),
            "fm_se_MKT_RF": float(np.std(mkt_rf, ddof=1) / np.sqrt(len(dates))),
            "fm_se_VAL": float(np.std(val, ddof=1) / np.sqrt(len(dates))),
            "fm_cs_r2": 1.0,
            "fm_pricing_rmse": 0.0,
        },
        "expected_capm": {
            # Because MKT_RF and VAL are exactly orthogonal, CAPM beta == true MKT_RF beta
            # and CAPM alpha_i == beta_VAL_i * mean(VAL)
            "alphas": {
                aid: float(b["VAL"] * np.mean(val)) for aid, b in true_betas.items()
            },
            "betas_MKT_RF": {aid: float(b["MKT_RF"]) for aid, b in true_betas.items()},
        },
    }
    (out_dir / "expected_oracle.json").write_text(
        json.dumps(oracle, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def generate_synthetic_ff3(seed: int = 42) -> None:
    """Generate 15-year (180-month) synthetic 25-portfolio FF3 + noise-MOM dataset."""
    out_dir = FIXTURES_DIR / "synthetic_ff3"
    rng = np.random.default_rng(seed)

    n_months = 180  # 2010-01-31 to 2024-12-31 (120 train, 60 test)
    dates = month_end_dates(2010, 1, n_months)

    # Monthly risk-free rate oscillating gently around 0.15% - 0.30%/month
    t_grid = np.arange(n_months, dtype=np.float64)
    rf = 0.0020 + 0.0008 * np.sin(2.0 * np.pi * t_grid / 120.0)

    # True monthly factor premia (decimal returns per month)
    true_premia = {
        "MKT_RF": 0.0070,  # 8.4% annualized
        "SMB": 0.0040,     # 4.8% annualized
        "HML": 0.0050,     # 6.0% annualized
        "MOM": 0.0010,     # 1.2% annualized (unloaded in true FF3 DGP)
    }

    # Factor covariance matrix (monthly volatilities: MKT 4.2%, SMB 1.6%, HML 1.6%, MOM 2.5%)
    means = np.array(
        [true_premia["MKT_RF"], true_premia["SMB"], true_premia["HML"], true_premia["MOM"]],
        dtype=np.float64,
    )
    vols = np.array([0.042, 0.016, 0.016, 0.025], dtype=np.float64)
    corr = np.array(
        [
            [1.00, 0.15, -0.10, -0.15],
            [0.15, 1.00, -0.05, 0.00],
            [-0.10, -0.05, 1.00, -0.20],
            [-0.15, 0.00, -0.20, 1.00],
        ],
        dtype=np.float64,
    )
    cov = np.outer(vols, vols) * corr
    factors = rng.multivariate_normal(mean=means, cov=cov, size=n_months)

    # 25 synthetic Size x Value test portfolios (5x5 grid) with exact zero true alpha under FF3.
    # Market betas include independent cross-sectional dispersion orthogonal to (SMB, HML)
    # so the Fama-MacBeth beta design matrix [1, b_MKT, b_SMB, b_HML] is well-conditioned.
    size_grid = np.linspace(1.1, -0.7, 5)    # Small (+1.1) to Big (-0.7) SMB loadings
    val_grid = np.linspace(-0.8, 1.0, 5)     # Growth (-0.8) to Value (+1.0) HML loadings
    mkt_dispersion = rng.uniform(0.65, 1.45, size=(5, 5))

    true_betas: dict[str, dict[str, float]] = {}
    asset_ids: list[str] = []
    for s_idx, b_smb in enumerate(size_grid, start=1):
        for v_idx, b_hml in enumerate(val_grid, start=1):
            aid = f"S{s_idx}V{v_idx}"
            asset_ids.append(aid)
            b_mkt = float(mkt_dispersion[s_idx - 1, v_idx - 1])
            true_betas[aid] = {
                "MKT_RF": round(b_mkt, 4),
                "SMB": round(float(b_smb), 4),
                "HML": round(float(b_hml), 4),
                "MOM": 0.0,
            }

    # Idiosyncratic monthly volatility of 0.8% per diversified test portfolio
    idio_std = 0.008
    rf_rows = [{"date": d, "rf": f"{rf[t]:.6f}"} for t, d in enumerate(dates)]
    factor_rows = [
        {
            "date": d,
            "MKT_RF": f"{factors[t, 0]:.6f}",
            "SMB": f"{factors[t, 1]:.6f}",
            "HML": f"{factors[t, 2]:.6f}",
            "MOM": f"{factors[t, 3]:.6f}",
        }
        for t, d in enumerate(dates)
    ]

    asset_rows: list[dict[str, object]] = []
    mem_rows: list[dict[str, object]] = []
    for t, d in enumerate(dates):
        eps_t = rng.normal(0.0, idio_std, size=len(asset_ids))
        for j, aid in enumerate(asset_ids):
            b = true_betas[aid]
            exc = (
                b["MKT_RF"] * factors[t, 0]
                + b["SMB"] * factors[t, 1]
                + b["HML"] * factors[t, 2]
                + eps_t[j]
            )
            tot = exc + rf[t]
            asset_rows.append(
                {"date": d, "asset_id": aid, "total_return": f"{tot:.6f}"}
            )
            mem_rows.append({"date": d, "asset_id": aid, "in_universe": "true"})

    _write_csv(out_dir / "risk_free.csv", ["date", "rf"], rf_rows)
    _write_csv(
        out_dir / "factor_returns.csv",
        ["date", "MKT_RF", "SMB", "HML", "MOM"],
        factor_rows,
    )
    _write_csv(out_dir / "asset_returns.csv", ["date", "asset_id", "total_return"], asset_rows)
    _write_csv(
        out_dir / "portfolio_memberships.csv",
        ["date", "asset_id", "in_universe"],
        mem_rows,
    )

    ground_truth = {
        "provenance": "Synthetic 25-portfolio Size x Value panel generated from a 3-factor DGP (zero true alpha under FF3).",
        "seed": seed,
        "n_months": n_months,
        "n_assets": len(asset_ids),
        "date_start": dates[0],
        "date_end": dates[-1],
        "idio_std_monthly": idio_std,
        "true_factor_premia_monthly": true_premia,
        "realized_factor_means_full_sample": {
            "MKT_RF": float(np.mean(factors[:, 0])),
            "SMB": float(np.mean(factors[:, 1])),
            "HML": float(np.mean(factors[:, 2])),
            "MOM": float(np.mean(factors[:, 3])),
        },
        "realized_factor_means_train_2010_2019": {
            "MKT_RF": float(np.mean(factors[:120, 0])),
            "SMB": float(np.mean(factors[:120, 1])),
            "HML": float(np.mean(factors[:120, 2])),
            "MOM": float(np.mean(factors[:120, 3])),
        },
        "true_betas": true_betas,
    }
    (out_dir / "ground_truth.json").write_text(
        json.dumps(ground_truth, indent=2, sort_keys=True) + "\n", encoding="utf-8"
    )


def generate_universe_change_fixture(seed: int = 101) -> None:
    """Generate 48-month panel with deterministic mid-sample asset exit and entry."""
    out_dir = FIXTURES_DIR / "universe_change"
    rng = np.random.default_rng(seed)
    dates = month_end_dates(2019, 1, 48)
    rf = np.full(48, 0.0015, dtype=np.float64)
    mkt = rng.normal(0.007, 0.04, size=48)
    hml = rng.normal(0.003, 0.025, size=48)

    assets = [
        ("CORE_1", 0.85, -0.4, 0, 48),
        ("CORE_2", 1.00, 0.0, 0, 48),
        ("CORE_3", 1.15, 0.4, 0, 48),
        ("CORE_4", 1.30, 0.8, 0, 48),
        ("CORE_5", 0.95, 0.5, 0, 48),
        ("EXIT_M24", 1.05, -0.2, 0, 24),    # active months 0..23, exits at month 24
        ("ENTRY_M25", 1.10, 0.6, 24, 48),   # enters at month 24..47
    ]

    rf_rows = [{"date": d, "rf": f"{rf[t]:.6f}"} for t, d in enumerate(dates)]
    factor_rows = [
        {"date": d, "MKT_RF": f"{mkt[t]:.6f}", "HML": f"{hml[t]:.6f}"}
        for t, d in enumerate(dates)
    ]
    asset_rows: list[dict[str, object]] = []
    mem_rows: list[dict[str, object]] = []

    for t, d in enumerate(dates):
        for aid, bm, bh, start_t, end_t in assets:
            in_u = start_t <= t < end_t
            eps = float(rng.normal(0.0, 0.01))
            tot = bm * mkt[t] + bh * hml[t] + eps + rf[t]
            # Include raw returns for all dates to verify PIT membership filtering drops inactive periods
            asset_rows.append({"date": d, "asset_id": aid, "total_return": f"{tot:.6f}"})
            mem_rows.append(
                {"date": d, "asset_id": aid, "in_universe": "true" if in_u else "false"}
            )

    _write_csv(out_dir / "risk_free.csv", ["date", "rf"], rf_rows)
    _write_csv(out_dir / "factor_returns.csv", ["date", "MKT_RF", "HML"], factor_rows)
    _write_csv(out_dir / "asset_returns.csv", ["date", "asset_id", "total_return"], asset_rows)
    _write_csv(
        out_dir / "portfolio_memberships.csv",
        ["date", "asset_id", "in_universe"],
        mem_rows,
    )


def generate_invalid_fixtures() -> None:
    """Generate explicit failure/boundary fixtures for missing RF, rank deficiency, and misalignment."""
    ref_dir = FIXTURES_DIR / "reference_hand_calculated"
    base_assets = (ref_dir / "asset_returns.csv").read_text(encoding="utf-8")
    base_factors = (ref_dir / "factor_returns.csv").read_text(encoding="utf-8")
    base_rf = (ref_dir / "risk_free.csv").read_text(encoding="utf-8")
    base_mem = (ref_dir / "portfolio_memberships.csv").read_text(encoding="utf-8")

    # 1. Missing risk-free observations (drop 2 dates from risk_free.csv)
    miss_dir = FIXTURES_DIR / "invalid" / "missing_rf"
    miss_dir.mkdir(parents=True, exist_ok=True)
    (miss_dir / "asset_returns.csv").write_text(base_assets, encoding="utf-8")
    (miss_dir / "factor_returns.csv").write_text(base_factors, encoding="utf-8")
    (miss_dir / "portfolio_memberships.csv").write_text(base_mem, encoding="utf-8")
    rf_lines = base_rf.strip().splitlines()
    # Keep header and drop 2020-03-31 and 2020-05-31
    kept_rf = [ln for ln in rf_lines if not ln.startswith(("2020-03-31", "2020-05-31"))]
    (miss_dir / "risk_free.csv").write_text("\n".join(kept_rf) + "\n", encoding="utf-8")

    # 2. Rank-deficient factor matrix (FAC_COLLINEAR = 2 * MKT_RF + 0.005)
    rank_dir = FIXTURES_DIR / "invalid" / "rank_deficient_factors"
    rank_dir.mkdir(parents=True, exist_ok=True)
    (rank_dir / "asset_returns.csv").write_text(base_assets, encoding="utf-8")
    (rank_dir / "risk_free.csv").write_text(base_rf, encoding="utf-8")
    (rank_dir / "portfolio_memberships.csv").write_text(base_mem, encoding="utf-8")
    fac_rows: list[dict[str, object]] = []
    with (ref_dir / "factor_returns.csv").open("r", encoding="utf-8") as fh:
        for row in csv.DictReader(fh):
            mkt_val = float(row["MKT_RF"])
            fac_rows.append(
                {
                    "date": row["date"],
                    "MKT_RF": row["MKT_RF"],
                    "VAL": row["VAL"],
                    "FAC_COLLINEAR": f"{2.0 * mkt_val + 0.005:.6f}",
                }
            )
    _write_csv(
        rank_dir / "factor_returns.csv",
        ["date", "MKT_RF", "VAL", "FAC_COLLINEAR"],
        fac_rows,
    )

    # 3. Misaligned periods (shift factor dates by 1 month: 2020-02-29 .. 2020-07-31)
    mis_dir = FIXTURES_DIR / "invalid" / "misaligned_periods"
    mis_dir.mkdir(parents=True, exist_ok=True)
    (mis_dir / "asset_returns.csv").write_text(base_assets, encoding="utf-8")
    (mis_dir / "risk_free.csv").write_text(base_rf, encoding="utf-8")
    (mis_dir / "portfolio_memberships.csv").write_text(base_mem, encoding="utf-8")
    shifted_dates = month_end_dates(2020, 2, 6)
    shifted_fac_rows: list[dict[str, object]] = []
    with (ref_dir / "factor_returns.csv").open("r", encoding="utf-8") as fh:
        for idx, row in enumerate(csv.DictReader(fh)):
            shifted_fac_rows.append(
                {
                    "date": shifted_dates[idx],
                    "MKT_RF": row["MKT_RF"],
                    "VAL": row["VAL"],
                }
            )
    _write_csv(
        mis_dir / "factor_returns.csv",
        ["date", "MKT_RF", "VAL"],
        shifted_fac_rows,
    )


def main() -> None:
    generate_reference_hand_calculated()
    generate_synthetic_ff3(seed=42)
    generate_universe_change_fixture(seed=101)
    generate_invalid_fixtures()
    print(f"Generated deterministic fixtures under {FIXTURES_DIR}")


if __name__ == "__main__":
    main()
